-- Күнделікті еске салу қай күні жіберілгенін белгілейтін баған.
--
-- Бұрын хабар "15 минуттық терезе" бойынша жіберілетін: cron сол аралықта
-- бір рет шақырылмаса, адам сол күні еске салуды мүлдем алмайтын. Енді
-- уақыты жеткен соң жіберіледі де, осы баған "бүгін жіберілді" деп
-- белгіленеді — кезекті cron кешігіп қалса да еске салу жоғалмайды,
-- әрі бір күнде екі рет жіберілмейді.

alter table reading_goals
  add column if not exists last_reminder_date date;

comment on column reading_goals.last_reminder_date is
  'Күнделікті еске салу соңғы рет жіберілген күн (Asia/Almaty).';
