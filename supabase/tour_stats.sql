-- Танысу туры бойынша статистика.
--
-- Бұрын тек tour_version бағаны болды, ал ол турдың қалай біткеніне
-- қарамайды: адам соңына дейін өтсе де, бірінші қадамда жауып кетсе де
-- бірдей мән жазылатын. Сондықтан «неше адам көрді» мен «неше адам
-- аяқтады» дегенді бөліп көрсету мүмкін емес еді.
--
-- tour_started_at   — тур бірінші қадамнан басталған сәт
-- tour_completed_at — «Дайын» батырмасына жетіп, соңына дейін өткен сәт
--
-- Екеуі де бір рет жазылады: қайта көрген адамның алғашқы мерзімі
-- сақталып қалады.
--
-- Ескерту: бұл бағандар бүгіннен бастап толады. Бұрын турды көріп
-- қойғандар туралы дерек жоқ — оларды tour_version арқылы бөлек
-- санаймыз.

alter table profiles
  add column if not exists tour_started_at timestamptz,
  add column if not exists tour_completed_at timestamptz;

comment on column profiles.tour_started_at is
  'Танысу туры басталған сәт. Бос болса — тур басталмаған немесе есеп қосылғанға дейін көрген.';

comment on column profiles.tour_completed_at is
  'Танысу туры соңына дейін өтілген сәт. Бос болса — аяқталмаған.';
