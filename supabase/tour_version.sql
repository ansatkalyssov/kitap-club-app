-- Танысу турын кім көргенін белгілейтін баған.
--
-- Сан түрінде: кейін турға жаңа бет қосылса, TOUR_VERSION-ды көтереміз де,
-- ескі оқырмандарға тур қайта көрсетіледі. Егер қарапайым true/false
-- болса, ондай мүмкіндік болмас еді.
--
-- 0 — тур әлі көрсетілмеген. Бұрыннан тіркелген оқырмандардың бәрі
-- осы мәнмен қалады, яғни келесі кіргенінде тур бір рет көрсетіледі.

alter table profiles
  add column if not exists tour_version integer not null default 0;

comment on column profiles.tour_version is
  'Оқырман көрген танысу турының нұсқасы. 0 — әлі көрмеген.';
