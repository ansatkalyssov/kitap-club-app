-- Танысу турында оқырман қай қадамға дейін жеткені.
--
-- Қадамның нөмірі (0-ден басталады, TOUR_STEPS тізбегіндегі реті). Ең
-- алысқа жеткен қадам сақталады: «Артқа» басып қайтса да, сан төмендемейді.
--
-- Бұл тек тур жабылғандағы мәнді емес, жолдың өзін көрсетеді. Адам турды
-- жаппай-ақ бетті тастап кетсе, соңғы белгісі осы бағанда қалады —
-- әйтпесе оның қай жерде тоқтағанын білу мүмкін емес еді.
--
-- 0 — бірінші қадамға жеткен (немесе әлі бастамаған; екеуін ажырату үшін
-- tour_started_at бағаны бар).

alter table profiles
  add column if not exists tour_last_step integer not null default 0;

comment on column profiles.tour_last_step is
  'Танысу турында жеткен ең алыс қадамның реті (0-ден басталады).';
