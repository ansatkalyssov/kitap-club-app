/**
 * Кестені толық оқиды.
 *
 * Supabase бір сұраныста ең көбі max_rows (әдетте 1000) жол қайтарады да,
 * қалғанын үнсіз тастап кетеді. Әкімші есептері бүкіл тарихты қажет
 * етеді, сондықтан бетпе-бет жүктейміз.
 *
 * build() әр бетке жаңа сұраныс құруы керек және оның реті тұрақты
 * болуы керек (бірегей бағанмен аяқталсын), әйтпесе беттер арасында
 * жол қайталанып не жоғалып кетеді.
 *
 * Тоқтау шарты — бос бет. «Бет толмады» деп тоқтасақ, max_rows біз
 * күткеннен аз болғанда тағы да үнсіз қиылар едік.
 */
export async function fetchAll<T = any>(
  build: () => any,
  pageSize = 1000
): Promise<{ data: T[] }> {
  const rows: T[] = [];
  for (;;) {
    const { data, error } = await build().range(rows.length, rows.length + pageSize - 1);
    // Жартылай дерек — қате сан. Үнсіз жалғастырғаннан гөрі құлағаны жөн.
    if (error) throw error;
    if (!data || data.length === 0) break;
    rows.push(...data);
  }
  return { data: rows };
}
